MONTHS_SHORT_RU = ("Янв", "Фев", "Мар", "Апр", "Май", "Июн", "Июл", "Авг", "Сен", "Окт",
                   "Ноя", "Дек")


def month_label(name: str, year=None) -> str:
    shown = t("month." + name, name)
    return f"{shown} {year}" if year else shown


def month_short(name: str) -> str:
    if LANG == "ru" and name in MONTHS:
        return MONTHS_SHORT_RU[MONTHS.index(name)]
    return name[:3]


def span_label(span: str) -> str:
    return month_label(span) if span == "undated" else span


def guide(english: tuple) -> tuple:
    return _GUIDES.get(LANG, english)


