from __future__ import annotations

import re

LANGS = ("en", "ru")
NAMES = {"en": "English", "ru": "Русский"}

LANG = "en"


def set_lang(code) -> None:
    global LANG
    LANG = code if code in LANGS else "en"


def t(key: str, english: str, **values) -> str:
    table = _TABLES.get(LANG)
    if table is not None and key in table:
        try:
            return fill(table[key], values)
        except (KeyError, ValueError, TypeError):
            pass
    try:
        return fill(english, values)
    except (KeyError, ValueError, TypeError):
        return english


_FIELD = re.compile(r"\{(\w+)(?:\|([^{}]*))?\}")


def fill(template: str, values: dict) -> str:
    def one(match: re.Match) -> str:
        value = values[match.group(1)]
        if match.group(2) is None:
            return str(value)
        forms = match.group(2).split("|")
        if len(forms) != 3:
            raise ValueError(f"a plural takes three forms: {match.group(0)}")
        return plural(value, *forms)

    return _FIELD.sub(one, template)


def plural(n, one: str, few: str, many: str) -> str:
    try:
        number = float(n)
    except (TypeError, ValueError):
        return many
    if not number.is_integer():
        return many
    whole = abs(int(number))
    if whole % 10 == 1 and whole % 100 != 11:
        return one
    if 2 <= whole % 10 <= 4 and not 12 <= whole % 100 <= 14:
        return few
    return many


